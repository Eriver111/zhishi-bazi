  function normalizePattern(pattern) {
    var value = typeof pattern === 'string' ? pattern.trim() : '';
    var i;

    if (Object.prototype.hasOwnProperty.call(SUPPORTED_PATTERNS, value)) return value;
    for (i = 0; i < KEYWORD_RULES.length; i += 1) {
      if (value.indexOf(KEYWORD_RULES[i][0]) !== -1) return KEYWORD_RULES[i][1];
    }
    return '杂格';
  }

  function resolve(options) {
    var input = options || {};
    var dayGan = input.bazi && input.bazi.day && input.bazi.day.gan;
    var identity = DAY_MASTERS[dayGan];
    var patternName;
    var genderKey;

    patternName = normalizePattern(input.pattern);
    genderKey = input.gender === 'female' ? 'female' : 'male';

    return {
      dayGan: dayGan,
      dayMasterLabel: dayGan + identity.element + (genderKey === 'female' ? '女' : '男'),
      subtitle: identity.subtitle,
      patternName: patternName,
      copyLines: COPY_MATRIX[dayGan][patternName].slice(),
      backgroundKey: identity.stem + '-' + genderKey,
      sealText: '知时',
      footer: '知天时，见自己',
    };
  }

